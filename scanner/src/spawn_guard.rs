//! Pins every way to silence the `disallowed-methods` ban on
//! `std::process::Command::new` (workspace `clippy.toml`, #599).
//!
//! Clippy is the enforcement: CI's `cargo clippy --workspace
//! --all-targets -- -D warnings` fails on a git spawn that bypasses
//! [`crate::git_command`] however the program name is spelled, in `src/`
//! and `tests/` alike (#588). These tests make widening that escape hatch
//! a visible change even under a plain `cargo test`: a new `allow` or
//! `expect` (bare or inside `cfg_attr`) of the lint, its `clippy::style`
//! or `clippy::all` group, or `warnings`, on any item or crate-wide, in
//! either workspace crate; an exemption moving to another item; the ban
//! leaving `clippy.toml`; a crate-level `clippy.toml` or `.cargo` config
//! shadowing it; or a `[lints]` table, crate or workspace, overriding it.
//!
//! Not caught: `-A` flags passed to clippy itself, and a silencer
//! generated by a macro.

use std::path::Path;

/// Lint names that silence the ban: the lint itself and its pre-rename
/// alias `disallowed_method`, the `clippy::style` and `clippy::all`
/// groups that contain it, and `warnings`. Matched token-wise, so
/// `clippy :: all` is the same name.
const SILENCERS: [&[&str]; 5] = [
    &["clippy", "::", "disallowed_methods"],
    &["clippy", "::", "disallowed_method"],
    &["clippy", "::", "style"],
    &["clippy", "::", "all"],
    &["warnings"],
];

/// The exemptions that are allowed: (file, silencer, item).
const PINNED: [(&str, &str, &str); 4] = [
    (
        "scanner/src/lib.rs",
        "clippy::disallowed_methods",
        "fn git_command",
    ),
    (
        "scanner/src/lib.rs",
        "clippy::disallowed_methods",
        "fn run_with_env",
    ),
    (
        "scanner/src/pr/mod.rs",
        "clippy::disallowed_methods",
        "fn hostile_home_fails_a_plain_commit",
    ),
    (
        "scanner/src/validate.rs",
        "clippy::disallowed_methods",
        "fn npx",
    ),
];

#[derive(Clone, Copy, Debug, PartialEq)]
enum Tok<'a> {
    Ident(&'a str),
    Punct(&'a str),
}

/// Rust source as a token stream with comments and string, char and raw
/// string literals dropped, so nothing inside them is matched. A byte
/// string `b"…"` lexes as the ident `b` plus a dropped string. Lifetimes
/// lex as an `'` punct plus an ident, which is all a lint scan needs.
fn tokens(src: &str) -> Vec<Tok<'_>> {
    let b = src.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    let skip_quoted = |mut i: usize, q: u8| {
        while i < b.len() && b[i] != q {
            i += if b[i] == b'\\' { 2 } else { 1 };
        }
        i + 1
    };
    while i < b.len() {
        let c = b[i];
        if c.is_ascii_whitespace() {
            i += 1;
        } else if b[i..].starts_with(b"//") {
            i = src[i..].find('\n').map_or(b.len(), |n| i + n);
        } else if b[i..].starts_with(b"/*") {
            // Bytes, not `&str` slices: this loop steps one byte at a
            // time, so `i` can sit inside a multibyte char here.
            let mut depth = 0;
            while i < b.len() {
                if b[i..].starts_with(b"/*") {
                    depth += 1;
                    i += 2;
                } else if b[i..].starts_with(b"*/") {
                    depth -= 1;
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    i += 1;
                }
            }
        } else if c == b'"' {
            i = skip_quoted(i + 1, b'"');
        } else if (c == b'r' || c == b'b') && raw_string_hashes(&src[i..]).is_some() {
            let (prefix, hashes) = raw_string_hashes(&src[i..]).unwrap();
            let close = format!("\"{}", "#".repeat(hashes));
            let body = i + prefix;
            i = src[body..]
                .find(&close)
                .map_or(b.len(), |n| body + n + close.len());
        } else if c == b'\'' && is_char_literal(&src[i..]) {
            i = skip_quoted(i + 1, b'\'');
        } else if c.is_ascii_alphanumeric() || c == b'_' || c >= 0x80 {
            let start = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_' || b[i] >= 0x80) {
                i += 1;
            }
            out.push(Tok::Ident(&src[start..i]));
        } else if b[i..].starts_with(b"::") {
            out.push(Tok::Punct("::"));
            i += 2;
        } else {
            out.push(Tok::Punct(&src[i..i + 1]));
            i += 1;
        }
    }
    out
}

/// For `r"`, `r#"`, `br##"`…: (bytes up to and including the opening
/// quote, number of hashes).
fn raw_string_hashes(s: &str) -> Option<(usize, usize)> {
    let rest = s.strip_prefix("br").or_else(|| s.strip_prefix('r'))?;
    let hashes = rest.bytes().take_while(|&c| c == b'#').count();
    (rest.as_bytes().get(hashes) == Some(&b'"'))
        .then(|| (s.len() - rest.len() + hashes + 1, hashes))
}

/// A `'` opens a char literal, not a lifetime, when the one char after
/// it is followed by a closing `'`: `'a'`, `'é'`, or an escape such as
/// `'\n'` or `'\''`. `s` starts at the opening quote.
fn is_char_literal(s: &str) -> bool {
    let mut chars = s[1..].chars();
    match chars.next() {
        Some('\\') => true,
        Some(_) => chars.next() == Some('\''),
        None => false,
    }
}

/// One silencing attribute found in a file.
#[derive(Debug, PartialEq)]
struct Silencer {
    lint: String,
    item: String,
}

/// Every lint attribute in `src` that names a [`SILENCERS`] entry inside
/// an `allow(` or `expect(`, anywhere in the attribute (so `cfg_attr`
/// counts), with the item it applies to.
fn silencers(src: &str) -> Vec<Silencer> {
    let t = tokens(src);
    let mut found = Vec::new();
    let mut i = 0;
    while i < t.len() {
        if t[i] != Tok::Punct("#") {
            i += 1;
            continue;
        }
        let inner = t.get(i + 1) == Some(&Tok::Punct("!"));
        let open = i + 1 + usize::from(inner);
        if t.get(open) != Some(&Tok::Punct("[")) {
            i += 1;
            continue;
        }
        let Some(close) = matching(&t, open) else {
            break;
        };
        let body = &t[open + 1..close];
        let silences = body
            .windows(2)
            .any(|w| matches!(w, [Tok::Ident("allow" | "expect"), Tok::Punct("(")]));
        if silences {
            for lint in SILENCERS {
                let hit = body.windows(lint.len()).any(|w| {
                    w.iter().zip(lint.iter()).all(
                        |(tok, want)| matches!(tok, Tok::Ident(s) | Tok::Punct(s) if s == want),
                    )
                });
                if hit {
                    let item = if inner {
                        "<inner attribute>".to_string()
                    } else {
                        item_after(&t, close + 1)
                    };
                    found.push(Silencer {
                        lint: lint.concat(),
                        item,
                    });
                }
            }
        }
        i = close + 1;
    }
    found
}

/// Index of the bracket closing the one at `open`.
fn matching(t: &[Tok<'_>], open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (k, tok) in t.iter().enumerate().skip(open) {
        match tok {
            Tok::Punct("[" | "(" | "{") => depth += 1,
            Tok::Punct("]" | ")" | "}") => {
                depth -= 1;
                if depth == 0 {
                    return Some(k);
                }
            }
            _ => {}
        }
    }
    None
}

/// The item an outer attribute ending before `k` applies to, skipping
/// any further attributes and the visibility and qualifier keywords:
/// `fn name`, or the keyword and name of whatever else is there.
fn item_after(t: &[Tok<'_>], mut k: usize) -> String {
    while t.get(k) == Some(&Tok::Punct("#")) && t.get(k + 1) == Some(&Tok::Punct("[")) {
        match matching(t, k + 1) {
            Some(c) => k = c + 1,
            None => return "<end of file>".to_string(),
        }
    }
    if t.get(k) == Some(&Tok::Ident("pub")) {
        k += 1;
        if t.get(k) == Some(&Tok::Punct("(")) {
            k = matching(t, k).map_or(t.len(), |c| c + 1);
        }
    }
    // `const`/`unsafe`/`async`/`extern` qualify a fn only when the run of
    // them ends in `fn`; otherwise `const X` is the item. An `extern`
    // ABI string is already gone from the token stream.
    let mut q = k;
    while matches!(
        t.get(q),
        Some(Tok::Ident("async" | "const" | "unsafe" | "extern"))
    ) {
        q += 1;
    }
    if q > k && t.get(q) == Some(&Tok::Ident("fn")) {
        k = q;
    }
    match (t.get(k), t.get(k + 1)) {
        (Some(Tok::Ident(kw)), Some(Tok::Ident(name))) => format!("{kw} {name}"),
        (Some(Tok::Ident(kw)), _) => format!("<{kw} …>"),
        (Some(Tok::Punct(p)), _) => format!("<{p} …>"),
        (None, _) => "<end of file>".to_string(),
    }
}

/// Every `.rs` file under the given workspace-relative directories,
/// skipping build output and hidden directories.
fn rust_files(workspace: &Path, dirs: &[&str]) -> Vec<std::path::PathBuf> {
    let mut stack: Vec<_> = dirs
        .iter()
        .map(|d| workspace.join(d))
        .filter(|d| d.is_dir())
        .collect();
    let mut files = Vec::new();
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).unwrap() {
            let path = entry.unwrap().path();
            let name = path.file_name().unwrap().to_string_lossy();
            if path.is_dir() {
                if name != "target" && !name.starts_with('.') {
                    stack.push(path);
                }
            } else if path.extension().is_some_and(|e| e == "rs") {
                files.push(path);
            }
        }
    }
    files
}

fn workspace() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap()
}

fn read(rel: &str) -> String {
    std::fs::read_to_string(workspace().join(rel)).unwrap()
}

/// TOML text with CRLF normalised, whole-line comments dropped and each
/// remaining line trimmed, so a commented-out entry does not count and
/// spacing or line endings do not matter.
fn live_toml(text: &str) -> String {
    text.replace("\r\n", "\n")
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Every `path = "..."` (or `'...'`) value in `clippy.toml`'s live
/// `disallowed-methods` table, read key by key outside TOML strings and
/// `#` comments, so entry field order, a `]` or `path =` inside a reason,
/// and a commented-out entry after a live one do not matter.
fn banned_paths(clippy_toml: &str) -> Vec<String> {
    let Some((_, rest)) = clippy_toml.split_once("disallowed-methods") else {
        return Vec::new();
    };
    let b = rest.as_bytes();
    let (mut i, mut depth, mut paths) = (0, 0usize, Vec::new());
    // Index of the closing quote. Basic `"..."` strings take `\` escapes;
    // literal `'...'` strings have none.
    let string_end = |mut i: usize, q: u8| {
        while i < b.len() && b[i] != q {
            i += if q == b'"' && b[i] == b'\\' { 2 } else { 1 };
        }
        i
    };
    while i < b.len() {
        match b[i] {
            b'[' => depth += 1,
            b']' => {
                // A `]` before any `[` means a malformed table: no ban.
                let Some(d) = depth.checked_sub(1) else { break };
                depth = d;
                if depth == 0 {
                    break;
                }
            }
            q @ (b'"' | b'\'') => i = string_end(i + 1, q),
            b'#' => i = rest[i..].find('\n').map_or(b.len(), |n| i + n),
            // A whole `path` key: not the tail of `reason_path` or
            // `x-path`, and not the head of `paths`.
            b'p' if depth > 0
                && b[i..].starts_with(b"path")
                && !matches!(
                    b[i - 1],
                    b'_' | b'-' | b'\'' | b'"' | b'0'..=b'9' | b'a'..=b'z' | b'A'..=b'Z'
                )
                && !matches!(
                    b.get(i + 4),
                    Some(b'_' | b'-' | b'0'..=b'9' | b'a'..=b'z' | b'A'..=b'Z')
                ) =>
            {
                let after = rest[i + 4..].trim_start();
                if let Some(value) = after.strip_prefix('=').map(str::trim_start)
                    && let Some(q) = value.chars().next().filter(|c| matches!(c, '"' | '\''))
                {
                    let body = &value[1..];
                    let end = body.find(q).unwrap_or(body.len());
                    paths.push(body[..end].to_string());
                }
            }
            _ => {}
        }
        i += 1;
    }
    paths
}

/// Whether a crate manifest inherits the workspace lints with no
/// crate-level `[lints.*]` override.
fn inherits_workspace_lints(manifest: &str) -> bool {
    let live = live_toml(manifest);
    live.contains("[lints]\nworkspace = true") && !live.contains("[lints.")
}

/// The body of the root manifest's `[workspace.lints.<tool>]` table, or
/// `None` when the table is missing.
fn workspace_lints(root: &str, tool: &str) -> Option<String> {
    let live = live_toml(root);
    let (_, rest) = live.split_once(&format!("[workspace.lints.{tool}]"))?;
    Some(rest.split("\n[").next().unwrap_or("").trim().to_string())
}

/// Every clippy config or cargo config under the crate directories that
/// would shadow the workspace `clippy.toml` (clippy reads the first one
/// it finds walking up from each crate, without merging) or could set
/// `CLIPPY_CONF_DIR`.
fn shadowing_configs(workspace: &Path, crates: &[&str]) -> Vec<String> {
    let mut found = Vec::new();
    let mut stack: Vec<_> = crates.iter().map(|c| workspace.join(c)).collect();
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries {
            let path = entry.unwrap().path();
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            if path.is_dir() {
                if name == ".cargo" {
                    found.push(path.strip_prefix(workspace).unwrap().display().to_string());
                } else if name != "target" && name != ".git" {
                    stack.push(path);
                }
            } else if name == "clippy.toml" || name == ".clippy.toml" {
                found.push(path.strip_prefix(workspace).unwrap().display().to_string());
            }
        }
    }
    for root_cargo in [".cargo/config", ".cargo/config.toml"] {
        let path = workspace.join(root_cargo);
        if path.exists()
            && std::fs::read_to_string(&path)
                .unwrap()
                .contains("CLIPPY_CONF_DIR")
        {
            found.push(root_cargo.to_string());
        }
    }
    found.sort();
    found
}

#[test]
fn the_ban_and_lint_levels_are_in_place() {
    let clippy_toml = live_toml(&read("clippy.toml"));
    assert!(
        banned_paths(&clippy_toml).contains(&"std::process::Command::new".to_string()),
        "clippy.toml must keep the live Command::new ban:\n{clippy_toml}"
    );
    for krate in ["scanner", "validator"] {
        assert!(
            inherits_workspace_lints(&read(&format!("{krate}/Cargo.toml"))),
            "{krate} must inherit the workspace lints unchanged"
        );
    }
    let root = read("Cargo.toml");
    assert_eq!(
        workspace_lints(&root, "clippy").as_deref(),
        Some("all = \"warn\""),
        "workspace clippy lints changed"
    );
    assert_eq!(
        workspace_lints(&root, "rust").as_deref(),
        Some("unsafe_code = \"forbid\""),
        "workspace rust lints changed; `warnings = \"allow\"` there silences the ban"
    );
    assert_eq!(
        shadowing_configs(workspace(), &["scanner", "validator"]),
        Vec::<String>::new(),
        "a crate-level clippy.toml or .cargo config would shadow the workspace ban"
    );
}

/// Each manifest check rejects the overrides it exists to catch, so a
/// regression in its parsing shows up here, not only against the repo.
#[test]
fn manifest_checks_reject_overrides() {
    let ok = "[package]\nname = \"x\"\n\n[lints]\nworkspace = true\n";
    assert!(inherits_workspace_lints(ok));
    assert!(inherits_workspace_lints(&ok.replace('\n', "\r\n")));
    for bad in [
        "[package]\nname = \"x\"\n",
        "[lints]\n# workspace = true\n",
        "[lints]\nworkspace = false\n",
        "[lints]\nworkspace = true\n[lints.clippy]\ndisallowed_methods = \"allow\"\n",
        "[lints.clippy]\ndisallowed_methods = \"allow\"\n",
    ] {
        assert!(!inherits_workspace_lints(bad), "accepted {bad:?}");
    }

    let root = |clippy: &str| {
        format!(
            "[workspace.lints.rust]\nunsafe_code = \"forbid\"\n\n[workspace.lints.clippy]\n{clippy}\n[profile.release]\nlto = true\n"
        )
    };
    assert_eq!(
        workspace_lints(&root("all = \"warn\""), "clippy").as_deref(),
        Some("all = \"warn\"")
    );
    assert_eq!(
        workspace_lints(&root("all = \"warn\"\n# style = \"allow\""), "clippy").as_deref(),
        Some("all = \"warn\"")
    );
    for bad in [
        "all = \"warn\"\ndisallowed_methods = \"allow\"",
        "all = \"warn\"\nstyle = \"allow\"",
        "all = \"allow\"",
    ] {
        assert_ne!(
            workspace_lints(&root(bad), "clippy").as_deref(),
            Some("all = \"warn\""),
            "accepted {bad:?}"
        );
    }
    assert_eq!(
        workspace_lints("[workspace]\nmembers = []\n", "clippy"),
        None
    );

    // The rust table is pinned too: `warnings = "allow"` there silences
    // every lint, the ban included.
    let with_rust = |rust: &str| {
        format!("[workspace.lints.rust]\n{rust}\n\n[workspace.lints.clippy]\nall = \"warn\"\n")
    };
    assert_eq!(
        workspace_lints(&with_rust("unsafe_code = \"forbid\""), "rust").as_deref(),
        Some("unsafe_code = \"forbid\"")
    );
    assert_ne!(
        workspace_lints(
            &with_rust("unsafe_code = \"forbid\"\nwarnings = \"allow\""),
            "rust"
        )
        .as_deref(),
        Some("unsafe_code = \"forbid\"")
    );
}

/// A clippy config or cargo config under a crate is reported, wherever
/// it sits, and build output is not walked.
#[test]
fn shadowing_configs_are_found() {
    let dir = tempfile::tempdir().unwrap();
    let ws = dir.path();
    for d in ["a/src", "b/target/debug", "c"] {
        std::fs::create_dir_all(ws.join(d)).unwrap();
    }
    assert_eq!(
        shadowing_configs(ws, &["a", "b", "c"]),
        Vec::<String>::new()
    );
    std::fs::write(ws.join("a/clippy.toml"), "").unwrap();
    std::fs::write(ws.join("a/src/.clippy.toml"), "").unwrap();
    std::fs::write(ws.join("b/target/debug/clippy.toml"), "").unwrap();
    std::fs::create_dir_all(ws.join("c/.cargo")).unwrap();
    std::fs::create_dir_all(ws.join(".cargo")).unwrap();
    std::fs::write(
        ws.join(".cargo/config.toml"),
        "[env]\nCLIPPY_CONF_DIR = \"x\"\n",
    )
    .unwrap();
    assert_eq!(
        shadowing_configs(ws, &["a", "b", "c"]),
        vec![
            ".cargo/config.toml",
            "a/clippy.toml",
            "a/src/.clippy.toml",
            "c/.cargo"
        ]
    );
}

#[test]
fn spawn_exemptions_are_pinned() {
    let ws = workspace();
    // Whole crates, so build.rs, benches/ and examples/ count too.
    let dirs = ["scanner", "validator"];
    let mut found = Vec::new();
    for path in rust_files(ws, &dirs) {
        let rel = path
            .strip_prefix(ws)
            .unwrap()
            .to_string_lossy()
            .into_owned();
        for s in silencers(&std::fs::read_to_string(&path).unwrap()) {
            found.push((rel.clone(), s.lint, s.item));
        }
    }
    found.sort();
    let want: Vec<_> = PINNED
        .iter()
        .map(|(f, l, i)| (f.to_string(), l.to_string(), i.to_string()))
        .collect();
    assert_eq!(
        found, want,
        "spawn git through crate::git_command(); a new Command::new exemption must be pinned in spawn_guard::PINNED"
    );
}

/// The ban is found whatever the entry's field order, and text that only
/// mentions the path inside a reason string does not count as a ban.
#[test]
fn banned_paths_reads_keys_not_text() {
    let cmd = "std::process::Command::new".to_string();
    for live in [
        "disallowed-methods = [\n{ path = \"std::process::Command::new\", reason = \"x\" },\n]",
        "disallowed-methods = [\n{ reason = \"see #[expect] ] here\", path = \"std::process::Command::new\" },\n]",
        "disallowed-methods=[{path=\"a::b\"},{path=\"std::process::Command::new\"}]",
        "disallowed-methods = [\n{ path = 'std::process::Command::new' },\n]",
        "disallowed-methods = [ # see #588\n{ reason = 'a ] b', path = \"std::process::Command::new\" },\n]",
    ] {
        assert!(
            banned_paths(live).contains(&cmd),
            "missed the ban in {live:?}"
        );
    }
    for dead in [
        "disallowed-methods = [\n{ path = \"a::b\", reason = \"not path = \\\"std::process::Command::new\\\"\" },\n]",
        "disallowed-methods = []\nother = [{ path = \"std::process::Command::new\" }]",
        "disallowed-types = [{ path = \"std::process::Command::new\" }]",
        "disallowed-methods = [{ reason_path = \"std::process::Command::new\" }]",
        "disallowed-methods = [{ x-path = \"std::process::Command::new\" }]",
        "disallowed-methods = [{ paths = \"std::process::Command::new\" }]",
        "disallowed-methods = ]\n[{ path = \"std::process::Command::new\" }]",
        "disallowed-methods = [\n{ path = \"a::b\" }, # { path = \"std::process::Command::new\" },\n]",
        "disallowed-methods = [\n{ path = \"a::b\", reason = 'path = \"std::process::Command::new\"' },\n]",
        "disallowed-methods = [\n{ path = \"a::b\", reason = 'a ] b' },\n]\nx = [{ path = \"std::process::Command::new\" }]",
    ] {
        assert!(!banned_paths(dead).contains(&cmd), "false ban in {dead:?}");
    }
}

/// Non-ASCII text inside a block comment is skipped with the comment and
/// never splits a char, so the silencer after it is still found.
#[test]
fn block_comments_may_hold_multibyte_text() {
    let src =
        "/* café — 😀 /* nested é */ ü */\n@[allow(clippy::all)]\nfn x() {}".replace('@', "#");
    let found: Vec<_> = silencers(&src)
        .into_iter()
        .map(|s| (s.lint, s.item))
        .collect();
    assert_eq!(found, vec![("clippy::all".to_string(), "fn x".to_string())]);
}

/// A char literal is told from a lifetime by its decoded first char, so
/// a multibyte char next to more multibyte text still closes where Rust
/// closes it.
#[test]
fn is_char_literal_decodes_whole_chars() {
    for lit in ["'a'", "'é',ü)", "'😀'", "'\\''", "'\\u{1F600}'", "'\"'"] {
        assert!(is_char_literal(lit), "{lit:?} is a char literal");
    }
    for lifetime in ["'a>", "'static str", "'é>", "'"] {
        assert!(!is_char_literal(lifetime), "{lifetime:?} is not");
    }
}

/// The scanner sees each silencer spelling, and nothing that only looks
/// like one. Fixtures are built at runtime so this file's own text holds
/// no attribute for `spawn_exemptions_are_pinned` to find.
#[test]
fn silencers_sees_every_spelling() {
    let attr = |s: &str| s.replace('@', "#");
    let lints = |src: &str| -> Vec<(String, String)> {
        silencers(&attr(src))
            .into_iter()
            .map(|s| (s.lint, s.item))
            .collect()
    };
    let one = |lint: &str, item: &str| vec![(lint.to_string(), item.to_string())];
    let dm = "clippy::disallowed_methods";

    assert_eq!(
        lints("@[allow(clippy::disallowed_methods)]\nfn a() {}"),
        one(dm, "fn a")
    );
    assert_eq!(
        lints("@ [ expect ( clippy :: disallowed_methods ) ]\npub(crate) fn b() {}"),
        one(dm, "fn b")
    );
    assert_eq!(
        lints("@[cfg_attr(test, allow(clippy::disallowed_methods))]\nfn c() {}"),
        one(dm, "fn c")
    );
    assert_eq!(
        lints("@[expect(reason = \"see @588 ]\", clippy::disallowed_methods)]\nfn d() {}"),
        one(dm, "fn d")
    );
    assert_eq!(
        lints("@[allow(clippy::disallowed_methods)]\n@[test]\n// note\nasync unsafe fn e() {}"),
        one(dm, "fn e")
    );
    assert_eq!(
        lints("@[allow(clippy::disallowed_methods)]\nconst X: u8 = 0;\nfn npx() {}"),
        one(dm, "const X")
    );
    assert_eq!(
        lints("@[allow(clippy::disallowed_methods)]\nmod m {}"),
        one(dm, "mod m")
    );
    assert_eq!(
        lints("@![allow(clippy::all)]"),
        one("clippy::all", "<inner attribute>")
    );
    assert_eq!(
        lints("@[allow(clippy::style)]\nfn f() {}"),
        one("clippy::style", "fn f")
    );
    assert_eq!(
        lints("@[expect(warnings)]\nfn g() {}"),
        one("warnings", "fn g")
    );
    assert_eq!(
        lints("@[allow(renamed_and_removed_lints, clippy::disallowed_method)]\nfn r() {}"),
        one("clippy::disallowed_method", "fn r")
    );

    // A literal that could swallow what follows it must end where Rust
    // ends it, so the real silencer after it is still found.
    for (lead, item) in [
        ("const Q: char = '\"';", "fn q"),
        ("const E: char = '\\'';", "fn q"),
        ("const U: char = 'é'; const V: char = '😀';", "fn q"),
        ("const B: &[u8] = b\"]\";", "fn q"),
        ("const R: &str = r@\"\"]\"@;", "fn q"),
        ("const L: &str = \"\\\"]\";", "fn q"),
        ("fn lt<'a>(_: &'a str) {}", "fn q"),
    ] {
        assert_eq!(
            lints(&format!(
                "{lead}\n@[allow(clippy::disallowed_methods)]\nfn q() {{}}"
            )),
            one(dm, item),
            "missed the silencer after {lead:?}"
        );
    }

    // Not silencers: comments, strings, other lints, other attributes.
    for quiet in [
        "// @[allow(clippy::disallowed_methods)]\nfn h() {}",
        "/* @[allow(clippy::all)] */ fn i() {}",
        "const S: &str = \"@[allow(clippy::disallowed_methods)]\";",
        "const R: &str = r@\"@[allow(warnings)]\"@;",
        "@[allow(unused_warnings)]\nfn j() {}",
        "@[allow(clippy::all_the_things)]\nfn k() {}",
        "@[deny(clippy::disallowed_methods)]\nfn l() {}",
        "@[doc = \"allow(clippy::disallowed_methods)\"]\nfn m() {}",
        "fn n<'a>(x: &'a str) -> char { let _ = x; 'x' }",
        "/* outer /* @[allow(clippy::all)] */ still comment @[allow(warnings)] */ fn o() {}",
        "const B: &[u8] = b\"@[allow(clippy::all)]\";",
        "const H: &str = r@@\"\"@ @[allow(warnings)] \"@@;",
    ] {
        assert_eq!(lints(quiet), Vec::new(), "false positive on {quiet:?}");
    }
}
